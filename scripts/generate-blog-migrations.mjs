// Generates one additive migration for each blog post added after the starter set
// (`laterBlogPosts` in lib/content/blogs.ts).
//
//   node scripts/generate-blog-migrations.mjs          writes the migrations
//   node scripts/generate-blog-migrations.mjs --check  exits 1 if a file on disk is out of date
//
// Why not just add the post to the seed? The seed (20261110200100_resource_modules_seed.sql) has
// already been run on the live database, only fills a table that is empty, and is wrapped into
// supabase/apply/05-resource-modules.sql, which people have already pasted. Editing it would
// change files that were applied, and would still not put the new post into a database that
// already has posts. So a later post gets its own file, which:
//
//   * says plainly if the blog_posts table is missing (run script 05 first),
//   * adds the post only if no post with that slug exists, so running it again changes nothing
//     and never overwrites an edit made in the admin,
//   * goes in published, dated the day it was written (midnight India time), and
//   * keeps the audit trigger off for the insert, as the seed does: a one-time import is not an
//     edit by a person.
//
// supabase/apply/06-… is the same SQL wrapped as one statement for the dashboard SQL editor
// (scripts/make-apply-blobs.mjs). Exports `buildBlogMigrations()` so
// tests/blog-directory.test.mjs can check the files on disk still match the content.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { json, load, q, stamp } from "./generate-resource-seed.mjs";

const root = new URL("../", import.meta.url);

/** One entry per post in `laterBlogPosts`. A test fails if a later post has no entry here. */
export const BLOG_MIGRATIONS = [
  {
    slug: "top-10-managed-it-services-companies-in-chennai",
    migration: "supabase/migrations/20261111120000_blog_top_10_managed_it_chennai.sql",
    apply: "supabase/apply/06-blog-top-10-managed-it-chennai.sql",
  },
];

const oneLine = (text) => text.replace(/\s+/g, " ").trim();

function migrationFor(post, entry) {
  return `-- Generated by scripts/generate-blog-migrations.mjs — do not edit by hand.
-- Adds the blog post "${oneLine(post.title)}" (/blogs/${post.slug}) to a database that
-- already has the blog_posts table (supabase/apply/05-resource-modules.sql).
--
-- Safe to run again. A post whose address (slug) already exists is left exactly as it is, so an
-- edit made in the admin is never overwritten. If an editor deletes the post, running this again
-- brings it back. It goes in published, dated ${post.publishedAt} (midnight India time), with the
-- audit trigger off for the insert because a one-time import is not an edit by a person.
-- ${entry.apply} is the same SQL as one statement for the dashboard SQL editor.

do $$
begin
  if to_regclass('public.blog_posts') is null then
    raise exception 'The blog_posts table does not exist yet. Run supabase/apply/05-resource-modules.sql first, then run this again.';
  end if;

  alter table public.blog_posts disable trigger c_audit;

  insert into public.blog_posts
    (slug, title, excerpt, category, reading_minutes, body, figure_seed, related_services,
     seo_title, seo_description, status, published_at)
  values
(
    ${q(post.slug)}, ${q(post.title)}, ${q(post.excerpt)}, ${q(post.category)}, null,
    ${json(post.body)}, ${post.figureSeed}, ${json(post.relatedServices)},
    ${q(post.seo.title)}, ${q(post.seo.description)}, 'published', ${stamp(post.publishedAt)}
  )
  on conflict (slug) do nothing;

  alter table public.blog_posts enable trigger c_audit;
end $$;
`;
}

export async function buildBlogMigrations() {
  const blogs = await load("lib/content/blogs.ts");
  return BLOG_MIGRATIONS.map((entry) => {
    const post = blogs.laterBlogPosts.find((candidate) => candidate.slug === entry.slug);
    if (!post) throw new Error(`No later blog post has the slug "${entry.slug}"`);
    return { ...entry, sql: migrationFor(post, entry) };
  });
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];

if (isMain) {
  const built = await buildBlogMigrations();
  let stale = false;

  for (const { migration, sql } of built) {
    const target = new URL(migration, root);

    if (process.argv.includes("--check")) {
      let current = "";
      try {
        current = readFileSync(target, "utf8");
      } catch {
        /* missing counts as out of date */
      }
      if (current !== sql) {
        console.error(`${migration} is out of date. Run: node scripts/generate-blog-migrations.mjs`);
        stale = true;
      } else {
        console.log(`${migration} is up to date.`);
      }
    } else {
      writeFileSync(target, sql);
      console.log(`Wrote ${migration}`);
    }
  }

  if (stale) process.exit(1);
}
