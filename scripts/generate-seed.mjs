// Generates supabase/seed.sql from the typed content that shipped with the
// frontend. Run with: node scripts/generate-seed.mjs
//
// The seed is guarded per table, so re-running it never overwrites edits made
// in the CMS. It exists to get the database to content parity on day one.

import { writeFileSync } from "node:fs";
import { services } from "../lib/content/services.ts";
import { industries } from "../lib/content/industries.ts";
import { insights } from "../lib/content/insights.ts";
import { legalDocuments } from "../lib/content/legal.ts";
import { faqGroups } from "../lib/content/faqs.ts";

const q = (value) => {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replaceAll("'", "''")}'`;
};

const json = (value) => `${q(JSON.stringify(value))}::jsonb`;

// Array from JSON avoids every array-literal escaping rule.
const textArray = (values) =>
  `array(select jsonb_array_elements_text(${json(values ?? [])}))::text[]`;

const stamp = (date) => (date ? q(`${date}T00:00:00+05:30`) : "null");

const blocks = [];

blocks.push(`-- Generated by scripts/generate-seed.mjs — do not edit by hand.
-- Content parity with the frontend seed. Each block is skipped when the table
-- already has rows, so this is safe to run once against an empty project.
`);

if (services.length) {
  const rows = services
    .map(
      (s) => `(
    ${q(s.slug)}, ${s.order}, ${q(s.name)}, ${q(s.shortName)}, ${q(s.tagline)},
    ${q(s.summary)}, ${q(s.intro)}, ${json(s.deliverables)}, ${textArray(s.outcomes)},
    ${json(s.faqs)}, ${textArray(s.related)}, ${json(s.figure)},
    ${q(s.seo.title)}, ${q(s.seo.description)}, 'published', null
  )`,
    )
    .join(",\n");

  blocks.push(`do $$
begin
  if not exists (select 1 from public.services) then
    insert into public.services
      (slug, sort_order, name, short_name, tagline, summary, intro, deliverables,
       outcomes, faqs, related, figure, seo_title, seo_description, status, published_at)
    values
${rows};
  end if;
end $$;`);
}

if (industries.length) {
  const rows = industries
    .map(
      (i, index) => `(
    ${q(i.slug)}, ${q(i.name)}, ${q(i.tagline)}, ${q(i.summary)},
    ${textArray(i.challenges)}, ${textArray(i.capabilities)}, ${textArray(i.services)},
    ${json(i.figure)}, ${q(i.seo.title)}, ${q(i.seo.description)}, ${index + 1}, 'published', null
  )`,
    )
    .join(",\n");

  blocks.push(`do $$
begin
  if not exists (select 1 from public.industries) then
    insert into public.industries
      (slug, name, tagline, summary, challenges, capabilities, services, figure,
       seo_title, seo_description, sort_order, status, published_at)
    values
${rows};
  end if;
end $$;`);
}

if (insights.length) {
  const rows = insights
    .map(
      (i) => `(
    ${q(i.slug)}, ${q(i.title)}, ${q(i.excerpt)}, ${q(i.category)}, ${i.readingMinutes},
    ${stamp(i.publishedAt)}, ${json(i.body)}, ${q(i.seo.title)}, ${q(i.seo.description)},
    'published'
  )`,
    )
    .join(",\n");

  blocks.push(`do $$
begin
  if not exists (select 1 from public.insights) then
    insert into public.insights
      (slug, title, excerpt, category, reading_minutes, published_at, body,
       seo_title, seo_description, status)
    values
${rows};
  end if;
end $$;`);
}

if (legalDocuments.length) {
  const rows = legalDocuments
    .map(
      (d) => `(
    ${q(d.slug)}, ${q(d.title)}, ${q(d.description)}, ${q(d.updated)}, ${q(d.intro)},
    ${json(d.sections)}, ${q(d.title)}, ${q(d.description)}, 'published', null
  )`,
    )
    .join(",\n");

  blocks.push(`do $$
begin
  if not exists (select 1 from public.legal_documents) then
    insert into public.legal_documents
      (slug, title, description, updated_label, intro, sections,
       seo_title, seo_description, status, published_at)
    values
${rows};
  end if;
end $$;`);
}

if (faqGroups.length) {
  const rows = faqGroups
    .map(
      (g, index) => `(
    ${q(g.title)}, ${q(g.intro)}, ${index + 1}, ${json(g.items)}, 'published', null
  )`,
    )
    .join(",\n");

  blocks.push(`do $$
begin
  if not exists (select 1 from public.faq_groups) then
    insert into public.faq_groups
      (title, intro, sort_order, items, status, published_at)
    values
${rows};
  end if;
end $$;`);
}

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), `${blocks.join("\n\n")}\n`);
console.log(`Wrote supabase/seed.sql (${services.length} services, ${industries.length} industries, ${insights.length} insights, ${legalDocuments.length} legal, ${faqGroups.length} FAQ groups)`);
