// Generates supabase/migrations/20261110200100_resource_modules_seed.sql from the typed content
// that shipped in code: the 18 sub-services, the three starter blog posts and the three
// representative case studies. (White papers start empty on purpose.)
//
//   node scripts/generate-resource-seed.mjs          writes the migration
//   node scripts/generate-resource-seed.mjs --check  exits 1 if the file on disk is out of date
//
// The result is guarded per table, like supabase/seed.sql: each block inserts only into a table
// that has no rows yet, so running it again never overwrites edits made in the admin and never
// brings back something an editor deleted. Rows go in with the audit trigger switched off,
// because a one-time import is not an edit by a person and would otherwise add 24 "System"
// lines to the audit log.
//
// The content modules are TypeScript. They are compiled in memory with the project's own
// TypeScript and loaded from data: URLs, the same way the unit tests do it; the modules
// that are loaded import only types, which the compiler removes.
//
// Exports `buildResourceSeed()` so tests/resource-modules.test.mjs can check that the file on
// disk still matches the content.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = new URL("../", import.meta.url);
export const SEED_PATH = "supabase/migrations/20261110200100_resource_modules_seed.sql";

async function load(path) {
  const source = readFileSync(new URL(path, root), "utf8");
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  });
  return import(`data:text/javascript;base64,${Buffer.from(outputText).toString("base64")}`);
}

const q = (value) => {
  if (value === null || value === undefined) return "null";
  const text = String(value);
  // The blocks are wrapped in $$ … $$; a literal $$ in the content would end them early.
  if (text.includes("$$")) throw new Error(`Content contains "$$", which cannot be seeded: ${text.slice(0, 60)}`);
  return `'${text.replaceAll("'", "''")}'`;
};

const json = (value) => `${q(JSON.stringify(value))}::jsonb`;

// An array built from JSON avoids every array-literal escaping rule.
const textArray = (values) => `array(select jsonb_array_elements_text(${json(values ?? [])}))::text[]`;

// A calendar date is midnight in India (the operating timezone), not midnight UTC.
const stamp = (date) => (date ? q(`${date}T00:00:00+05:30`) : "null");

function guarded(table, columns, rows) {
  return `do $$
begin
  if not exists (select 1 from public.${table}) then
    alter table public.${table} disable trigger c_audit;

    insert into public.${table}
      (${columns})
    values
${rows.join(",\n")};

    alter table public.${table} enable trigger c_audit;
  end if;
end $$;`;
}

export async function buildResourceSeed() {
  const [subservices, blogs, studies] = await Promise.all([
    loadSubservices(),
    load("lib/content/blogs.ts"),
    load("lib/content/case-studies.ts"),
  ]);

  const posts = blogs.blogPosts; // in the order they were written
  const caseStudies = studies.caseStudies;

  const blocks = [
    `-- Generated by scripts/generate-resource-seed.mjs — do not edit by hand.
-- The sub-services, blog posts and case studies that shipped in code, copied into the tables
-- from 20261110200000_resource_modules.sql so nothing on the public site disappears when the
-- site starts reading them from the database. Each block is skipped when its table already has
-- rows, so this is safe to run again and never overwrites edits made in the admin. White papers
-- start empty: none have been published.
`,
  ];

  blocks.push(
    guarded(
      "sub_services",
      "parent_slug, slug, sort_order, name, tagline, summary, intro, deliverables, outcomes, faqs,\n       infographic, figure, seo_title, seo_description, status, published_at",
      subservices.map(
        (s) => `(
    ${q(s.parentSlug)}, ${q(s.slug)}, ${s.order}, ${q(s.name)}, ${q(s.tagline)},
    ${q(s.summary)}, ${q(s.intro)}, ${json(s.deliverables)}, ${textArray(s.outcomes)},
    ${json(s.faqs)}, ${s.infographic ? json(s.infographic) : "null"}, ${json(s.figure)},
    ${q(s.seo.title)}, ${q(s.seo.description)}, 'published', null
  )`,
      ),
    ),
  );

  blocks.push(
    guarded(
      "blog_posts",
      "slug, title, excerpt, category, reading_minutes, body, figure_seed, related_services,\n       seo_title, seo_description, status, published_at",
      posts.map(
        (p) => `(
    ${q(p.slug)}, ${q(p.title)}, ${q(p.excerpt)}, ${q(p.category)}, null,
    ${json(p.body)}, ${p.figureSeed}, ${json(p.relatedServices)},
    ${q(p.seo.title)}, ${q(p.seo.description)}, 'published', ${stamp(p.publishedAt)}
  )`,
      ),
    ),
  );

  blocks.push(
    guarded(
      "case_studies",
      "slug, title, sector, kind, client_name, client_approved, situation, work, result, services,\n       sort_order, seo_title, seo_description, status, published_at",
      caseStudies.map(
        (c, index) => `(
    ${q(c.slug)}, ${q(c.title)}, ${q(c.sector)}, ${q(c.kind)}, ${q(c.clientName)}, false,
    ${q(c.situation)}, ${textArray(c.work)}, ${q(c.result)}, ${textArray(c.services)},
    ${index + 1}, ${q(c.seo.title)}, ${q(c.seo.description)}, 'published', null
  )`,
      ),
    ),
  );

  return {
    sql: `${blocks.join("\n\n")}\n`,
    counts: { subServices: subservices.length, blogPosts: posts.length, caseStudies: caseStudies.length },
  };
}

/**
 * subservices.ts imports the three code lists by relative path, which a data: URL cannot
 * resolve, so the lists are loaded one by one and joined with the same function the app uses.
 */
async function loadSubservices() {
  const [model, cyber, cloud, product] = await Promise.all([
    load("lib/content/subservice-model.ts"),
    load("lib/content/cybersecurity-subservices.ts"),
    load("lib/content/cloud-subservices.ts"),
    load("lib/content/product-subservices.ts"),
  ]);
  return model.normalizeSubservices({
    cybersecurity: cyber.cybersecuritySubservices,
    cloud: cloud.cloudSubservices,
    product: product.productSubservices,
  });
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];

if (isMain) {
  const { sql, counts } = await buildResourceSeed();
  const target = new URL(SEED_PATH, root);

  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      /* missing counts as out of date */
    }
    if (current !== sql) {
      console.error(`${SEED_PATH} is out of date. Run: node scripts/generate-resource-seed.mjs`);
      process.exit(1);
    }
    console.log(`${SEED_PATH} is up to date.`);
  } else {
    writeFileSync(target, sql);
    console.log(
      `Wrote ${SEED_PATH} (${counts.subServices} sub-services, ${counts.blogPosts} blog posts, ${counts.caseStudies} case studies)`,
    );
  }
}
